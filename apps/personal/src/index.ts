// Configure auto-updater
autoUpdater.autoDownload = true;
autoUpdater.autoInstallOnAppQuit = true;

// Use generic provider with our own update server to avoid
// "Latest" release collision between B2B and B2C apps in the same repo.
// The /api/updates/personal endpoint finds the latest personal-v* release.
autoUpdater.setFeedURL({
  provider: 'generic',
  url: 'https://www.sequ3nce.ai/api/updates/personal',
});
// Do NOT set autoUpdater.channel — the default "latest" channel makes
// electron-updater request latest-mac.yml / latest.yml, which matches
// the manifest filenames in the GitHub release assets.

// Set up auto-updater event handlers
function setupAutoUpdater() {
  autoUpdater.on('checking-for-update', () => {
    console.log('[AutoUpdate] Checking for updates...');
  });

  autoUpdater.on('update-available', (info) => {
    console.log('[AutoUpdate] Update available:', info.version);
    // Notify the renderer that an update is available
    if (mainWindow && !mainWindow.isDestroyed()) {
      mainWindow.webContents.send('update:available', info);
    }
  });

  autoUpdater.on('update-not-available', (info) => {
    console.log('[AutoUpdate] App is up to date:', info.version);
  });

  autoUpdater.on('download-progress', (progress) => {
    console.log(`[AutoUpdate] Download progress: ${progress.percent.toFixed(1)}%`);
    if (mainWindow && !mainWindow.isDestroyed()) {
      mainWindow.webContents.send('update:progress', progress);
    }
  });

  autoUpdater.on('update-downloaded', (info) => {
    console.log('[AutoUpdate] Update downloaded:', info.version);

    // Only show dialog if window is still valid
    if (mainWindow && !mainWindow.isDestroyed()) {
      dialog.showMessageBox(mainWindow, {
        type: 'info',
        title: 'Update Ready',
        message: `A new version (${info.version}) has been downloaded.`,
        detail: 'Restart now to apply the update?',
        buttons: ['Restart Now', 'Later'],
        defaultId: 0,
      }).then((result) => {
        if (result.response === 0) {
          isQuitting = true;
          autoUpdater.quitAndInstall();
        }
      });
    } else {
      // Window was closed, install on next launch
      console.log('[AutoUpdate] Window destroyed, update will install on next launch');
    }
  });

  autoUpdater.on('error', (error) => {
    console.error('[AutoUpdate] Error:', error);
  });

  // Check for updates on startup (after a short delay)
  setTimeout(() => {
    autoUpdater.checkForUpdates().catch((err) => {
      console.error('[AutoUpdate] Failed to check for updates:', err);
    });
  }, 5000);

  // Check for updates every 4 hours
  setInterval(() => {
    autoUpdater.checkForUpdates().catch((err) => {
      console.error('[AutoUpdate] Failed to check for updates:', err);
    });
  }, 4 * 60 * 60 * 1000);
}

// IPC handler for manual update check
ipcMain.handle('update:check', async () => {
  try {
    const result = await autoUpdater.checkForUpdates();
    return { success: true, version: result?.updateInfo?.version };
  } catch (error) {
    console.error('[AutoUpdate] Manual check failed:', error);
    return { success: false, error: String(error) };
  }
});

// IPC handler for installing update
ipcMain.handle('update:install', () => {
  isQuitting = true;
  autoUpdater.quitAndInstall();
});

  // Open window.open / <a target="_blank"> links in the system browser
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    try {
      const parsed = new URL(url);
      if (parsed.protocol === 'http:' || parsed.protocol === 'https:') {
        shell.openExternal(url);
      }
    } catch { /* ignore invalid URLs */ }
    return { action: 'deny' };
  });

  // Show window when ready — renderer sets correct size synchronously before paint
  mainWindow.once('ready-to-show', () => {
    mainWindow?.show();
  });

  // Prevent window from closing, minimize to tray instead.
  // If we're in native macOS fullscreen, hiding synchronously leaves the Space
  // black — we must exit fullscreen first and hide once the transition ends.
  mainWindow.on('close', (event) => {
    if (isQuitting) return;
    event.preventDefault();
    if (!mainWindow) return;

    if (mainWindow.isFullScreen()) {
      mainWindow.once('leave-full-screen', () => {
        mainWindow?.hide();
      });
      mainWindow.setFullScreen(false);
    } else {
      mainWindow.hide();
    }
  });

  // Open DevTools in development
  if (process.env.NODE_ENV === 'development' || process.defaultApp) {
    mainWindow.webContents.openDevTools({ mode: 'detach' });
  }

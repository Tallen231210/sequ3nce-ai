// This method will be called when Electron has finished initialization
app.whenReady().then(() => {
  // Register protocol first
  registerProtocol();

  createWindow();
  createTray();
  setupIpcHandlers();
  setupAutoUpdater(); // Initialize auto-updater

  // B2C Personal app uses server-side meeting bots — no local audio permissions needed

  // Initialize Sequ3nce Stream (hold-to-talk dictation)
  // Wrapped in try/catch so any Stream failure cannot break the rest of the app.
  try {
    initializeStream();
  } catch (err) {
    console.error('[Main] initializeStream failed:', err);
  }

  // Grant permission requests from renderers for the APIs video calling needs.
  // Electron defaults to *deny* on all permission prompts, so Daily.co's
  // getUserMedia() + getDisplayMedia() calls fail silently without this.
  // We scope the grant narrowly — only the permissions an in-app video call
  // legitimately needs. macOS still enforces its own system-level prompts on
  // top of this (Camera/Microphone/Screen Recording under System Settings).
  session.defaultSession.setPermissionRequestHandler(
    (_webContents, permission, callback) => {
      const allowed = new Set([
        'media',                      // camera + mic (getUserMedia)
        'display-capture',            // screen sharing (getDisplayMedia)
        // navigator.clipboard.writeText() — without this, the share-modal
        // Copy button silently fails when Chromium routes the write through
        // the permission system (post-await timing in handleGenerate, focus
        // edge cases). Restores the pre-handler default-grant for clipboard.
        'clipboard-sanitized-write',
      ]);
      callback(allowed.has(permission));
    }
  );

  // Display-media request handler — fires when the renderer calls
  // navigator.mediaDevices.getDisplayMedia() (which Daily's startScreenShare
  // does internally). We DEFER the callback: store it + the source list,
  // notify the renderer via 'display-media:request' so it can show our
  // ScreenSharePickerModal, then wait for the renderer to pick (or cancel)
  // via the 'app:select-display-media-source' IPC handler above. That call
  // fires the stored callback with the chosen source, which gives Daily a
  // proper MediaStream and the share actually streams to viewers.
  //
  // useSystemPicker is FALSE because (a) it requires macOS 15 Sequoia and
  // (b) when active it suppresses our callback entirely on macOS 15+. Our
  // custom picker works the same on every macOS version.
  session.defaultSession.setDisplayMediaRequestHandler(
    async (_request, callback) => {
      try {
        const sources = await desktopCapturer.getSources({
          types: ['screen', 'window'],
          thumbnailSize: { width: 320, height: 200 },
          fetchWindowIcons: true,
        });
        // If a previous picker is still pending (e.g. user clicked Share
        // twice) cancel it cleanly before replacing.
        if (pendingDisplayMedia) {
          pendingDisplayMedia.callback({});
        }
        pendingDisplayMedia = { callback, sources };
        const win = mainWindow ?? BrowserWindow.getAllWindows()[0];
        if (!win) {
          // No renderer to ask — fall back to first source.
          pendingDisplayMedia = null;
          callback(sources[0] ? { video: sources[0] } : {});
          return;
        }
        win.webContents.send(
          'display-media:request',
          sources.map((s) => ({
            id: s.id,
            name: s.name,
            type: s.id.startsWith('screen:') ? 'screen' : 'window',
            thumbnail: s.thumbnail.toDataURL(),
            appIcon: s.appIcon && !s.appIcon.isEmpty() ? s.appIcon.toDataURL() : null,
          })),
        );
      } catch (err) {
        console.error('[setDisplayMediaRequestHandler] failed:', err);
        callback({});
      }
    },
    { useSystemPicker: false }
  );

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) {
      createWindow();
    } else {
      mainWindow?.show();
    }
  });
});

// Handle protocol URL on macOS

interface MacOSVersion {
  name: string;
  version: number;
  darwin: number;
}

function getMacOSVersion(): MacOSVersion {
  const release = os.release(); // e.g., "24.1.0" for Sequoia
  const majorVersion = parseInt(release.split('.')[0], 10);

  // Darwin version to macOS version mapping:
  // Darwin 24.x = macOS 15.x (Sequoia)
  // Darwin 23.x = macOS 14.x (Sonoma)
  // Darwin 22.x = macOS 13.x (Ventura)
  // Darwin 21.x = macOS 12.x (Monterey)

  if (majorVersion >= 24) return { name: 'Sequoia', version: 15, darwin: majorVersion };
  if (majorVersion >= 23) return { name: 'Sonoma', version: 14, darwin: majorVersion };
  if (majorVersion >= 22) return { name: 'Ventura', version: 13, darwin: majorVersion };
  if (majorVersion >= 21) return { name: 'Monterey', version: 12, darwin: majorVersion };
  return { name: 'Older', version: 11, darwin: majorVersion };
}

